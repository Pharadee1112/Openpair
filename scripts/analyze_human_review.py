"""
analyze_human_review.py — human review vs keyword scorer (full-suite run)
=========================================================================
Reads paper/review_verdicts_old.tsv (one native Thai speaker, 462 answers judged blind
from their first 80 characters) plus machine scores from benchmark_results_*_full.json
and writes paper/HUMAN_REVIEW.md. No API calls.

  python scripts/analyze_human_review.py
"""

from __future__ import annotations

import csv
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VERDICTS = ROOT / "paper" / "review_verdicts_old.tsv"
OUT = ROOT / "paper" / "HUMAN_REVIEW.md"

# order must match the index after "|" in the code column of review_verdicts_old.tsv
MODELS = [
    ("gemini-3.1-flash-lite", "benchmark_results_gemini_full.json", "Gemini 3.1 Flash-Lite"),
    ("openai/gpt-oss-120b",   "benchmark_results_groq_full.json",   "gpt-oss-120b"),
    ("openai/gpt-oss-20b",    "benchmark_results_groq_full.json",   "gpt-oss-20b"),
]
CATEGORIES = ["qa", "translation", "classification", "creative"]


def load_machine() -> list[dict[str, dict]]:
    out = []
    for model_id, fname, _ in MODELS:
        data = json.loads((ROOT / fname).read_text(encoding="utf-8"))
        entry = next(m for m in data["models"] if m["model_id"] == model_id)
        out.append({s["id"]: s for s in entry["scores"]})
    return out


def pct(a: int, b: int) -> str:
    return f"{a}/{b} ({a / b:.0%})" if b else "–"


def main() -> None:
    machine = load_machine()
    rows = []
    with open(VERDICTS, encoding="utf-8", newline="") as f:
        for r in csv.DictReader(f, delimiter="\t"):
            case_id, idx = r["code"].split("|")
            m = machine[int(idx)][case_id]
            rows.append({"case": case_id, "cat": m["category"], "model": int(idx),
                         "human": r["verdict"], "passed": m["passed"], "score": m["final_score"],
                         "note": r["note"], "note_en": r.get("note_en", "")})

    md: list[str] = []
    w = md.append
    w("# Human review vs machine scores\n")
    w("> Generated by `python scripts/analyze_human_review.py` — do not edit by hand.")
    w(f"> One native Thai speaker judged {len(rows)} answers blind (154 cases × 3 models) from the "
      "first 80 characters stored by the full-suite run.")
    w("> Y = correct, N = wrong, `?` = cut off before it could be judged (excluded from rates). "
      "Raw reviewer notes are Thai; English translations are in the `note_en` column of `review_verdicts_old.tsv`.\n")

    w("## 1. Correct answers (decidable only)\n")
    w("| Model | Correct (Y) | Wrong (N) | Undecidable (?) | Correct rate |")
    w("|---|---:|---:|---:|---:|")
    for i, (_, _, label) in enumerate(MODELS):
        c = Counter(r["human"] for r in rows if r["model"] == i)
        w(f"| {label} | {c['Y']} | {c['N']} | {c['?']} | {pct(c['Y'], c['Y'] + c['N'])} |")
    w("")

    w("## 2. Correct rate by category\n")
    w("| Category | " + " | ".join(l for _, _, l in MODELS) + " |")
    w("|---|" + "---:|" * len(MODELS))
    for cat in CATEGORIES:
        cells = []
        for i in range(len(MODELS)):
            c = Counter(r["human"] for r in rows if r["model"] == i and r["cat"] == cat)
            cells.append(f"{pct(c['Y'], c['Y'] + c['N'])} (? {c['?']})")
        w(f"| {cat} | " + " | ".join(cells) + " |")
    w("")

    judged = [r for r in rows if r["human"] in ("Y", "N")]
    w("## 3. Does the keyword scorer agree with the human? (decidable only)\n")
    w("| Model | Agree | Machine pass, human wrong | Machine fail, human correct |")
    w("|---|---:|---:|---:|")
    for i, (_, _, label) in enumerate(MODELS):
        j = [r for r in judged if r["model"] == i]
        agree = sum((r["human"] == "Y") == r["passed"] for r in j)
        fp = sum(r["passed"] and r["human"] == "N" for r in j)
        fn = sum(not r["passed"] and r["human"] == "Y" for r in j)
        w(f"| {label} | {pct(agree, len(j))} | {fp} | {fn} |")
    agree = sum((r["human"] == "Y") == r["passed"] for r in judged)
    fp_all = [r for r in judged if r["passed"] and r["human"] == "N"]
    w(f"| **All** | {pct(agree, len(judged))} | {len(fp_all)} | "
      f"{sum(not r['passed'] and r['human'] == 'Y' for r in judged)} |")
    w("")
    ny = [r["score"] for r in judged if r["human"] == "N"]
    yy = [r["score"] for r in judged if r["human"] == "Y"]
    w(f"Mean machine score of answers the human marked **wrong** = {sum(ny) / len(ny):.2f} / 10; "
      f"marked **correct** = {sum(yy) / len(yy):.2f} / 10\n")

    w("## 4. Examples: machine pass, human wrong\n")
    w("| Case | Model | Machine score | Reviewer note (EN) | Reviewer note (TH, raw) |")
    w("|---|---|---:|---|---|")
    for r in sorted(fp_all, key=lambda r: -r["score"]):
        w(f"| `{r['case']}` | {MODELS[r['model']][2]} | {r['score']:.1f} "
          f"| {r['note_en'] or '–'} | {r['note'] or '–'} |")
    w("")

    OUT.write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
